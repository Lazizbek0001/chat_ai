from pydantic import BaseModel, Field
import uuid
from typing import Literal

class MessageCreate(BaseModel):

    content: str



class MessageResponse(BaseModel):

    id: uuid.UUID
    role: str
    content: str


    class Config:
        from_attributes = True



class ChatResponse(BaseModel):

    id: uuid.UUID
    title: str
    messages: list[MessageResponse]


    class Config:
        from_attributes = True

class LoginRequest(BaseModel):
    # Username or email.
    username: str = Field(min_length=1, max_length=320)
    password: str = Field(min_length=1, max_length=1024)


class UserCreate(BaseModel):
    username: str = Field(min_length=3, max_length=150, pattern=r"^[A-Za-z0-9_.-]+$")
    email: str | None = Field(default=None, min_length=3, max_length=320, pattern=r"^[^@\s]+@[^@\s]+$")
    password: str = Field(min_length=8, max_length=1024)
    is_superuser: bool = False


class PasswordChange(BaseModel):
    old_password: str = Field(min_length=1, max_length=1024)
    new_password: str = Field(min_length=8, max_length=1024)


class ChatRequest(BaseModel):
    # Message ids are generated by the server and returned in the response.
    message: str = Field(min_length=1)
    # From GET /chat/ai/models. Empty provider uses DEFAULT_AI_PROVIDER; empty model uses
    # that provider's default (GROQ_DEFAULT_MODEL / OLLAMA_DEFAULT_MODEL).
    provider: Literal["groq", "ollama"] | None = None
    model: str | None = None